

import numpy as np

#1D array  create

array_1D = np.array([1,2,3,4,5])

print("Print array: ", array_1D)
print("Print dimension: ", array_1D.ndim) #dimension
print("Print data type: ", array_1D.dtype) #data type
print("Print total element of array:", array_1D.size) #element
print("Print array of row and column: ",array_1D.shape) # row x column









#2D array create

